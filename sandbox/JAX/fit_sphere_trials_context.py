#!/usr/bin/env python3
"""JAX geodesic model with a multi-frame initial-condition encoder.

This is the original JAX learned-metric model applied to the archived
``fit_sphere_trials.py`` dataset.  A shared encoder consumes only the first
``JAX_CONTEXT_STEPS`` neural frames and predicts the latent initial position
and velocity.  The remaining heldout frames are generated by rolling the
learned geodesic dynamics forward; they are never encoder inputs.
"""

import json
import os
import time
from pathlib import Path

import jax
import jax.numpy as jnp
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import optax


jax.config.update("jax_enable_x64", True)


TRAIN_INDICES = np.array(
    [12, 0, 6, 25, 8, 15, 10, 18, 16, 23, 28, 26, 20, 7, 21, 22, 29, 13, 14, 2, 4, 1, 9, 11],
    dtype=np.int64,
)
HELDOUT_INDICES = np.array([17, 19, 27, 5, 24, 3], dtype=np.int64)


def init_mlp(keys, layer_sizes):
    params = []
    for index in range(len(layer_sizes) - 1):
        weights = jax.random.normal(keys[index], (layer_sizes[index], layer_sizes[index + 1]))
        weights = weights * jnp.sqrt(2.0 / layer_sizes[index])
        bias = jnp.zeros((layer_sizes[index + 1],))
        params.append((weights, bias))
    return params


def apply_mlp(params, values, final_activation=None):
    for weights, bias in params[:-1]:
        values = jax.nn.swish(jnp.dot(values, weights) + bias)
    weights, bias = params[-1]
    output = jnp.dot(values, weights) + bias
    if final_activation == "softplus":
        return jax.nn.softplus(output)
    return output


def init_model_params(key, n_cells, context_steps):
    """Initialize the original 2D encoder, metric, and decoder networks."""
    keys = jax.random.split(key, 3)

    # The only architectural change from the original JAX code: the encoder
    # consumes ten frames instead of two. It still outputs 2D z0 and 2D v0.
    encoder_keys = jax.random.split(keys[0], 4)
    encoder = init_mlp(encoder_keys, [n_cells * context_steps, 128, 128, 4])

    decoder_keys = jax.random.split(keys[1], 4)
    decoder = init_mlp(decoder_keys, [2, 128, 128, n_cells])

    metric_keys = jax.random.split(keys[2], 4)
    metric = init_mlp(metric_keys, [2, 64, 64, 3])
    metric[-1] = (
        jnp.zeros((64, 3)),
        jnp.array([1.0, 0.0, 0.37]),
    )
    return {"enc": encoder, "metric": metric, "dec": decoder}


def get_metric(metric_params, latent_position):
    lower_elements = apply_mlp(metric_params, latent_position)
    lower = jnp.array(
        [
            [jax.nn.softplus(lower_elements[0]) + 0.1, 0.0],
            [lower_elements[1], jax.nn.softplus(lower_elements[2]) + 0.1],
        ]
    )
    return lower @ lower.T + 1e-3 * jnp.eye(2)


def get_christoffel(metric_params, latent_position):
    metric = get_metric(metric_params, latent_position)
    inverse_metric = jnp.linalg.inv(metric)
    metric_jacobian = jax.jacobian(get_metric, argnums=1)(metric_params, latent_position)
    derivatives = jnp.transpose(metric_jacobian, (2, 0, 1))
    term_1 = jnp.einsum("imj->mij", derivatives)
    term_2 = jnp.einsum("jmi->mij", derivatives)
    term_3 = jnp.einsum("mij->mij", derivatives)
    christoffel_first_kind = 0.5 * (term_1 + term_2 - term_3)
    return jnp.einsum("mk,kij->mij", inverse_metric, christoffel_first_kind)


def geodesic_acceleration(latent_position, latent_velocity, metric_params):
    christoffel = get_christoffel(metric_params, latent_position)
    return -jnp.einsum("mij,i,j->m", christoffel, latent_velocity, latent_velocity)


def rk4_step(latent_position, latent_velocity, dt, metric_params):
    def derivative(state):
        position, velocity = state
        return velocity, geodesic_acceleration(position, velocity, metric_params)

    k1_position, k1_velocity = derivative((latent_position, latent_velocity))
    k2_position, k2_velocity = derivative(
        (
            latent_position + 0.5 * dt * k1_position,
            latent_velocity + 0.5 * dt * k1_velocity,
        )
    )
    k3_position, k3_velocity = derivative(
        (
            latent_position + 0.5 * dt * k2_position,
            latent_velocity + 0.5 * dt * k2_velocity,
        )
    )
    k4_position, k4_velocity = derivative(
        (latent_position + dt * k3_position, latent_velocity + dt * k3_velocity)
    )
    next_position = latent_position + (dt / 6.0) * (
        k1_position + 2 * k2_position + 2 * k3_position + k4_position
    )
    next_velocity = latent_velocity + (dt / 6.0) * (
        k1_velocity + 2 * k2_velocity + 2 * k3_velocity + k4_velocity
    )
    return next_position, next_velocity


def integrate_geodesic(initial_position, initial_velocity, n_steps, dt, metric_params):
    def step(state, _):
        position, velocity = state
        next_position, next_velocity = rk4_step(position, velocity, dt, metric_params)
        return (next_position, next_velocity), next_position

    _, remaining_positions = jax.lax.scan(
        step,
        (initial_position, initial_velocity),
        None,
        length=n_steps - 1,
    )
    return jnp.concatenate([initial_position[None, :], remaining_positions], axis=0)


def infer_initial_conditions(params, neural_sequence, context_steps):
    context = neural_sequence[:context_steps].reshape(-1)
    encoded = apply_mlp(params["enc"], context)
    return encoded[:2], encoded[2:]


def model_forward(params, neural_sequence, dt, context_steps):
    initial_position, initial_velocity = infer_initial_conditions(
        params, neural_sequence, context_steps
    )
    latent_trajectory = integrate_geodesic(
        initial_position,
        initial_velocity,
        neural_sequence.shape[0],
        dt,
        params["metric"],
    )
    predicted_activity = jax.vmap(apply_mlp, in_axes=(None, 0, None))(
        params["dec"], latent_trajectory, "softplus"
    )
    return predicted_activity


def batch_loss(params, neural_batch, dt, context_steps):
    losses = jax.vmap(
        lambda sequence: jnp.mean(
            (sequence - model_forward(params, sequence, dt, context_steps)) ** 2
        )
    )(neural_batch)
    return jnp.mean(losses)


def reconstruction_metrics(true_values, predicted_values):
    true_values = np.asarray(true_values, dtype=np.float64).reshape(-1)
    predicted_values = np.asarray(predicted_values, dtype=np.float64).reshape(-1)
    residual = true_values - predicted_values
    denominator = np.sum((true_values - true_values.mean()) ** 2)
    correlation = np.corrcoef(true_values, predicted_values)[0, 1]
    return {
        "mse": float(np.mean(residual**2)),
        "r2": float(1.0 - np.sum(residual**2) / denominator),
        "r": float(correlation),
    }


def sphere_centers(theta_centers, phi_centers):
    return np.stack(
        [
            np.sin(theta_centers) * np.cos(phi_centers),
            np.sin(theta_centers) * np.sin(phi_centers),
            np.cos(theta_centers),
        ],
        axis=-1,
    )


def activity_to_sphere(activity, place_cells):
    coordinates = np.asarray(activity) @ place_cells
    norms = np.linalg.norm(coordinates, axis=-1, keepdims=True)
    return coordinates / np.maximum(norms, 1e-12)


def plot_heldout_reconstruction(
    true_activity,
    predicted_activity,
    true_trajectory,
    place_cells,
    context_steps,
    output_path,
):
    predicted_trajectory = activity_to_sphere(predicted_activity, place_cells)
    figure = plt.figure(figsize=(18, 6))
    axis = figure.add_subplot(1, 3, 1, projection="3d")
    longitude, colatitude = np.mgrid[0 : 2 * np.pi : 30j, 0 : np.pi : 20j]
    axis.plot_wireframe(
        np.cos(longitude) * np.sin(colatitude),
        np.sin(longitude) * np.sin(colatitude),
        np.cos(colatitude),
        color="gray",
        alpha=0.18,
    )
    axis.plot(*true_trajectory.T, color="#12355B", linewidth=3, label="True")
    axis.plot(*predicted_trajectory.T, color="#FF5A1F", linewidth=3, label="Predicted")
    axis.set_title("Heldout trajectory")
    axis.legend()
    axis.set_axis_off()

    maximum = max(float(true_activity.max()), float(predicted_activity.max()))
    for panel, values, title in [
        (figure.add_subplot(1, 3, 2), true_activity.T, "Heldout activity"),
        (figure.add_subplot(1, 3, 3), predicted_activity.T, "Predicted activity"),
    ]:
        image = panel.imshow(
            values,
            aspect="auto",
            origin="lower",
            cmap="magma",
            vmin=0,
            vmax=maximum,
        )
        panel.axvline(context_steps - 0.5, color="white", linewidth=1.5)
        panel.set_xlabel("Frame")
        panel.set_title(title)
        figure.colorbar(image, ax=panel, fraction=0.046, pad=0.04)
    figure.axes[1].set_ylabel("Neuron")
    figure.savefig(output_path, dpi=180, bbox_inches="tight")
    plt.close(figure)


def main():
    data_path = Path(
        os.environ.get(
            "JAX_SPHERE_DATA_PATH",
            "runs/geodesic_sphere_forecast_2d_30x600_e3000_float64_cpu/"
            "synthetic_sphere_trials.npz",
        )
    ).expanduser()
    output_dir = Path(
        os.environ.get(
            "JAX_OUT_DIR",
            "runs/jax_sphere_2d_30x600_e3000_context10",
        )
    ).expanduser()
    output_dir.mkdir(parents=True, exist_ok=True)
    context_steps = int(os.environ.get("JAX_CONTEXT_STEPS", "10"))
    epochs = int(os.environ.get("JAX_EPOCHS", "3000"))
    learning_rate = float(os.environ.get("JAX_LR", "0.001"))
    log_every = int(os.environ.get("JAX_LOG_EVERY", "100"))
    early_stopping_patience = int(os.environ.get("JAX_EARLY_STOPPING_PATIENCE", "100"))
    early_stopping_min_delta = float(
        os.environ.get("JAX_EARLY_STOPPING_MIN_DELTA", "1e-6")
    )
    seed = int(os.environ.get("JAX_SEED", "42"))

    print(f"JAX devices: {jax.devices()}")
    print(f"Loading exact sphere data: {data_path}")
    with np.load(data_path) as source:
        all_activity = source["activities"].astype(np.float64)
        true_latents = source["true_latents"].astype(np.float64)
        theta_centers = source["theta_centers"].astype(np.float64)
        phi_centers = source["phi_centers"].astype(np.float64)
        time_points = source["t_eval"].astype(np.float64)

    if len(all_activity) != 30:
        raise ValueError("The fixed comparison split expects exactly 30 trials.")
    if not 2 <= context_steps < all_activity.shape[1]:
        raise ValueError("JAX_CONTEXT_STEPS must be at least 2 and shorter than a trial.")

    train_activity = all_activity[TRAIN_INDICES]
    heldout_activity = all_activity[HELDOUT_INDICES]
    train_data = jnp.asarray(train_activity)
    heldout_data = jnp.asarray(heldout_activity)
    n_train, n_steps, n_cells = train_activity.shape
    dt = float(time_points[1] - time_points[0])
    print(f"Train: {train_activity.shape}; heldout: {heldout_activity.shape}")
    print(
        f"Encoder context: first {context_steps} frames; forecast score: frames "
        f"{context_steps}-{n_steps - 1}"
    )

    params = init_model_params(jax.random.PRNGKey(seed), n_cells, context_steps)
    optimizer = optax.chain(optax.clip_by_global_norm(1.0), optax.adam(learning_rate))
    optimizer_state = optimizer.init(params)

    @jax.jit
    def train_step(current_params, current_optimizer_state, batch):
        loss, gradients = jax.value_and_grad(batch_loss)(
            current_params, batch, dt, context_steps
        )
        updates, next_optimizer_state = optimizer.update(
            gradients, current_optimizer_state, current_params
        )
        next_params = optax.apply_updates(current_params, updates)
        return next_params, next_optimizer_state, loss

    rng = np.random.default_rng(seed)
    loss_history = []
    best_loss = float("inf")
    best_epoch = -1
    best_params = params
    epochs_without_improvement = 0
    stop_reason = "completed_requested_epochs"
    print("Starting optimization...")
    start_time = time.time()
    for epoch in range(epochs):
        order = rng.permutation(n_train)
        params_before_update = params
        next_params, next_optimizer_state, loss = train_step(
            params, optimizer_state, train_data[order]
        )
        loss_value = float(loss)
        loss_history.append(loss_value)
        if not np.isfinite(loss_value):
            stop_reason = f"non_finite_loss_at_epoch_{epoch}"
            print(
                f"Non-finite loss at epoch {epoch}; restoring best epoch "
                f"{best_epoch} (MSE={best_loss:.8f})."
            )
            break

        if loss_value < best_loss - early_stopping_min_delta:
            best_loss = loss_value
            best_epoch = epoch
            best_params = params_before_update
            epochs_without_improvement = 0
        else:
            epochs_without_improvement += 1

        params = next_params
        optimizer_state = next_optimizer_state
        if epoch % log_every == 0 or epoch == epochs - 1:
            print(f"Epoch {epoch:04d} | Reconstruction MSE: {loss_value:.8f}")

        if epochs_without_improvement >= early_stopping_patience:
            stop_reason = f"early_stopping_at_epoch_{epoch}"
            print(
                f"Early stopping at epoch {epoch}; restoring best epoch "
                f"{best_epoch} (MSE={best_loss:.8f})."
            )
            break

    params = best_params
    epochs_completed = len(loss_history)
    elapsed_seconds = time.time() - start_time
    print(f"Optimization ran for {elapsed_seconds:.2f} seconds.")

    predict_batch = jax.jit(
        jax.vmap(lambda sequence: model_forward(params, sequence, dt, context_steps))
    )
    infer_batch = jax.jit(
        jax.vmap(lambda sequence: infer_initial_conditions(params, sequence, context_steps))
    )
    train_prediction = np.asarray(predict_batch(train_data))
    heldout_prediction = np.asarray(predict_batch(heldout_data))
    train_initial_position, train_initial_velocity = infer_batch(train_data)
    heldout_initial_position, heldout_initial_velocity = infer_batch(heldout_data)

    train_metrics = reconstruction_metrics(train_activity, train_prediction)
    heldout_context_metrics = reconstruction_metrics(
        heldout_activity[:, :context_steps], heldout_prediction[:, :context_steps]
    )
    forecast_metrics = reconstruction_metrics(
        heldout_activity[:, context_steps:], heldout_prediction[:, context_steps:]
    )
    print(
        f"Train R2: {train_metrics['r2']:.6f} | Train r: {train_metrics['r']:.6f} "
        f"| Train MSE: {train_metrics['mse']:.8f}"
    )
    print(
        f"Forecast R2: {forecast_metrics['r2']:.6f} | Forecast r: "
        f"{forecast_metrics['r']:.6f} | Forecast MSE: {forecast_metrics['mse']:.8f}"
    )

    theta = true_latents[..., 0]
    phi = true_latents[..., 1]
    true_trajectories = np.stack(
        [
            np.sin(theta) * np.cos(phi),
            np.sin(theta) * np.sin(phi),
            np.cos(theta),
        ],
        axis=-1,
    )
    place_cells = sphere_centers(theta_centers, phi_centers)
    plot_heldout_reconstruction(
        heldout_activity[0],
        heldout_prediction[0],
        true_trajectories[HELDOUT_INDICES[0]],
        place_cells,
        context_steps,
        output_dir / "heldout_reconstruction.png",
    )

    summary = {
        "config": {
            "data_path": str(data_path),
            "train_indices": TRAIN_INDICES.tolist(),
            "heldout_indices": HELDOUT_INDICES.tolist(),
            "num_train_trials": int(len(TRAIN_INDICES)),
            "num_heldout_trials": int(len(HELDOUT_INDICES)),
            "n_timepoints": int(n_steps),
            "n_neurons": int(n_cells),
            "latent_dim": 2,
            "context_steps": context_steps,
            "forecast_start_frame": context_steps,
            "epochs": epochs,
            "epochs_completed": epochs_completed,
            "best_epoch": best_epoch,
            "best_training_mse": best_loss,
            "early_stopping_patience": early_stopping_patience,
            "early_stopping_min_delta": early_stopping_min_delta,
            "stop_reason": stop_reason,
            "learning_rate": learning_rate,
            "dtype": "jax.float64",
            "solver": "rk4",
            "encoder_input": f"first_{context_steps}_neural_frames",
            "elapsed_seconds": elapsed_seconds,
        },
        "train": train_metrics,
        "heldout_context": heldout_context_metrics,
        "forecast": forecast_metrics,
    }
    (output_dir / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    np.savez_compressed(
        output_dir / "fit_outputs.npz",
        train_indices=TRAIN_INDICES,
        heldout_indices=HELDOUT_INDICES,
        train_activity=train_activity,
        heldout_activity=heldout_activity,
        train_prediction=train_prediction,
        heldout_prediction=heldout_prediction,
        train_initial_position=np.asarray(train_initial_position),
        train_initial_velocity=np.asarray(train_initial_velocity),
        heldout_initial_position=np.asarray(heldout_initial_position),
        heldout_initial_velocity=np.asarray(heldout_initial_velocity),
        true_latents=true_latents,
        theta_centers=theta_centers,
        phi_centers=phi_centers,
        time_points=time_points,
        mse_history=np.asarray(loss_history, dtype=np.float64),
    )
    print(f"Saved outputs to {output_dir}")


if __name__ == "__main__":
    main()
